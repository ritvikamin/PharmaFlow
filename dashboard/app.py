"""
app.py - the PharmaFlow Streamlit dashboard.

Run:   streamlit run dashboard/app.py        (after:  python run_all.py)

Streamlit re-runs this whole file from top to bottom every time you click something.
Every number on the page is READ from MySQL (views and tables); no KPI maths happens here.
"""
import os
import sys
import numpy as np
import pandas as pd
import streamlit as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import config      # noqa: E402
import forecast    # noqa: E402
import risk        # noqa: E402
import sample_upload  # noqa: E402

# chart colours: red = needs attention, amber = excess, blue / orange = two series
RED, AMBER, BLUE, ORANGE = "#e34948", "#eda100", "#2a78d6", "#eb6834"

st.set_page_config(page_title="PharmaFlow", layout="wide")


@st.cache_resource
def get_engine():
    return config.get_engine()


engine = get_engine()


@st.cache_data(ttl=120)
def read(sql):
    """Run a SELECT and return a table (cached for 2 minutes so clicks stay fast)."""
    return pd.read_sql(sql, engine)


# ---------------------------------------------------------------- start-up checks
try:
    as_of = read("SELECT as_of_date FROM v_as_of").iloc[0, 0]
    stock_risk = read("SELECT * FROM stock_risk")
except Exception as err:  # noqa: BLE001
    st.error("Could not read the PharmaFlow tables from MySQL. Run `python run_all.py` first, "
             "and check PF_DB_PASSWORD is set in this terminal.")
    st.exception(err)
    st.stop()

regions = read("SELECT region_name FROM dim_region ORDER BY region_id")["region_name"].tolist()

# ---------------------------------------------------------------- sidebar
st.sidebar.title("PharmaFlow")
region = st.sidebar.selectbox("Region", ["All regions"] + regions)
st.sidebar.caption("Filters the KPI cards, tables and charts.")
st.sidebar.markdown("---")
th = read("SELECT risk_days, excess_days FROM kpi_thresholds").iloc[0]
st.sidebar.write(f"**At risk:** fewer than {int(th.risk_days)} days until empty")
st.sidebar.write(f"**Excess:** more than {int(th.excess_days)} days of stock")
st.sidebar.markdown("---")
st.sidebar.caption("All data is synthetic (generated by this project).")

st.title("PharmaFlow: which medicines are about to run out, where, and why?")
st.caption(f"Data as of {as_of}. Synthetic data.")


def in_region(df, col="region_name"):
    """Keep only the chosen region (or everything for 'All regions')."""
    return df if region == "All regions" else df[df[col] == region]


# ---------------------------------------------------------------- KPI cards
risk_f = in_region(stock_risk)
so = in_region(read("SELECT * FROM v_stockout_rate_region"))
ot = in_region(read("SELECT * FROM v_on_time_delivery_site_region"))
val = read("SELECT * FROM forecast_validation")
val_all = val[val.scope == "All regions"].set_index("model")

stockout_rate = 100 * so.stockout_days.sum() / so.product_days.sum()
on_time_rate = 100 * ot.on_time.sum() / ot.shipments_due.sum()
n_risk = int((risk_f.status == "At risk").sum())
n_excess = int((risk_f.status == "Excess").sum())

c1, c2, c3, c4, c5 = st.columns(5)
c1.metric("Medicines at risk", n_risk, help="Product-region pairs with fewer days until empty than the threshold, using the 30-day forecast.")
c2.metric("Excess-stock items", n_excess, help="Pairs holding more days of stock than the excess threshold (expiry risk).")
c3.metric("Stockout rate", f"{stockout_rate:.2f}%", help="Share of product-days that ended with zero stock, over the whole history.")
c4.metric("On-time delivery", f"{on_time_rate:.1f}%", help="Delivered on/before promised date, among shipments already due. Undelivered due shipments count as late.")
c5.metric("Forecast error (backtest)", f"{val_all.loc['moving_average_14d', 'daily_wape_pct']:.1f}%",
          help="WAPE of the 14-day moving average on the last 30 days it had not seen. Lower is better.")
c5.caption(f"Naive baseline: {val_all.loc['naive_last_day', 'daily_wape_pct']:.1f}%")

# ---------------------------------------------------------------- at-risk table
st.subheader("Medicines needing attention")
cols = {"product_name": "Medicine", "region_name": "Region", "site_name": "Supplier plant",
        "units_on_hand": "Stock (units)", "forecast_daily_demand": "Forecast / day",
        "days_until_empty": "Days until empty", "reason": "Why"}
tab_risk, tab_excess = st.tabs([f"At risk ({n_risk})", f"Excess stock ({n_excess})"])
with tab_risk:
    t = risk_f[risk_f.status == "At risk"].sort_values("days_until_empty")[list(cols)].rename(columns=cols)
    if t.empty:
        st.success("No medicines are below the risk threshold in this region.")
    else:
        st.dataframe(t, hide_index=True, height=min(40 + 35 * len(t), 600))
with tab_excess:
    t = risk_f[risk_f.status == "Excess"].sort_values("days_until_empty", ascending=False)[list(cols)].rename(columns=cols)
    if t.empty:
        st.info("No excess-stock items in this region.")
    else:
        st.dataframe(t, hide_index=True)

# ---------------------------------------------------------------- two charts side by side
left, right = st.columns(2)

with left:
    st.subheader("On-time delivery by factory")
    by_site = ot.groupby("site_name")[["shipments_due", "on_time", "still_in_transit"]].sum()
    by_site["On-time %"] = (100 * by_site.on_time / by_site.shipments_due).round(1)
    st.bar_chart(by_site["On-time %"], color=BLUE)
    st.dataframe(by_site.rename(columns={"shipments_due": "Shipments due", "on_time": "On time",
                                         "still_in_transit": "Overdue, not delivered"}))

with right:
    st.subheader("Regional stock status")
    st.caption("Items needing attention, based on cover over the last 30 days of sales.")
    rs = in_region(read("SELECT * FROM v_region_stock_status"))
    chart = rs.set_index("region_name")[["insufficient_items", "excess_items"]].astype(int)
    chart.columns = ["Insufficient stock", "Excess stock"]
    st.bar_chart(chart, color=[RED, AMBER])
    show = rs.rename(columns={"region_name": "Region", "insufficient_items": "Insufficient",
                              "healthy_items": "Healthy", "excess_items": "Excess",
                              "shortage_units": "Shortage (units)", "excess_units": "Excess (units)"})
    st.dataframe(show, hide_index=True)

# ---------------------------------------------------------------- demand history + forecast
st.subheader("Demand: actual sales and 30-day forecast")
products = read("SELECT product_name FROM dim_product ORDER BY product_id")["product_name"].tolist()
product = st.selectbox("Medicine", products, index=products.index("Salbutamol Inhaler")
                       if "Salbutamol Inhaler" in products else 0)
reg_clause = "" if region == "All regions" else f"AND r.region_name = '{region}'"
hist = read(f"""SELECT d.full_date AS day, SUM(s.units_sold) AS Actual
                FROM fact_sales s JOIN dim_date d ON d.date_id = s.date_id
                JOIN dim_product p ON p.product_id = s.product_id
                JOIN dim_region r ON r.region_id = s.region_id
                WHERE p.product_name = '{product}' {reg_clause}
                GROUP BY d.full_date ORDER BY d.full_date DESC LIMIT 90""").sort_values("day")
fut = read(f"""SELECT f.forecast_date AS day, SUM(f.forecast_units) AS Forecast
               FROM forecast_daily f JOIN dim_product p ON p.product_id = f.product_id
               JOIN dim_region r ON r.region_id = f.region_id
               WHERE p.product_name = '{product}' {reg_clause}
               GROUP BY f.forecast_date ORDER BY f.forecast_date""")
hist["day"], fut["day"] = pd.to_datetime(hist["day"]), pd.to_datetime(fut["day"])
line = pd.concat([hist.set_index("day"), fut.set_index("day")], axis=1)
st.line_chart(line, color=[BLUE, ORANGE])
st.caption("The forecast is a flat line: the average of the last 14 days. It does not follow weekday swings, "
           "and it lags when demand is still rising.")

# ---------------------------------------------------------------- forecast validation
with st.expander("How good is the forecast? (backtest on the last 30 days)"):
    show = val_all.reset_index().rename(columns={
        "model": "Model", "daily_wape_pct": "Daily error % (WAPE)", "mae_units": "Avg miss (units/day)",
        "total30_wape_pct": "30-day total error %", "bias_pct": "Bias % (- = too low)"}).drop(columns="scope")
    st.dataframe(show, hide_index=True)
    st.caption("The model trained on all but the last 30 days and was scored on those 30 days. "
               "Lower is better; a forecast must beat the naive baselines to be worth using.")

# ---------------------------------------------------------------- CSV upload
st.subheader("Load new data")
if "upload_msg" in st.session_state:
    st.success(st.session_state.pop("upload_msg"))

with st.expander("Upload a CSV of new daily sales + inventory"):
    st.write("Columns required: `full_date, product_id, region_id, units_sold, units_on_hand`. "
             "Dates must come after the latest loaded day, and every date needs all product-region rows.")
    sample = sample_upload.make_sample(engine)
    st.download_button("Download a sample CSV (the next 7 days)", sample.to_csv(index=False),
                       file_name="sample_upload.csv", mime="text/csv")
    up = st.file_uploader("Choose CSV", type="csv")

    if up is not None:
        new = pd.read_csv(up)
        problems = []
        missing = [c for c in ["full_date", "product_id", "region_id", "units_sold", "units_on_hand"]
                   if c not in new.columns]
        if missing:
            problems.append(f"Missing columns: {missing}")
        else:
            new["full_date"] = pd.to_datetime(new["full_date"], errors="coerce")
            if new["full_date"].isna().any():
                problems.append("Some dates could not be read (use YYYY-MM-DD).")
            if (new[["units_sold", "units_on_hand"]] < 0).any().any():
                problems.append("units_sold and units_on_hand must not be negative.")
            known_p = set(read("SELECT product_id FROM dim_product").product_id)
            known_r = set(read("SELECT region_id FROM dim_region").region_id)
            if not set(new.product_id) <= known_p or not set(new.region_id) <= known_r:
                problems.append("Unknown product_id or region_id.")
            if new.duplicated(["full_date", "product_id", "region_id"]).any():
                problems.append("Duplicate date/product/region rows in the file.")
            if not problems:
                last_loaded = pd.Timestamp(pd.read_sql("SELECT as_of_date FROM v_as_of", engine).iloc[0, 0])  # fresh, not cached
                if new.full_date.min() <= last_loaded:
                    problems.append(f"Dates must be after the latest loaded day ({last_loaded.date()}).")
                n_pairs = len(known_p) * len(known_r)
                if (new.groupby("full_date").size() != n_pairs).any():
                    problems.append(f"Each date needs exactly {n_pairs} rows (every product in every region).")

        if problems:
            for p in problems:
                st.error(p)
        else:
            st.write(f"{len(new)} rows, {new.full_date.min().date()} to {new.full_date.max().date()}")
            if st.button("Load into MySQL and refresh KPIs"):
                new["date_id"] = new.full_date.dt.strftime("%Y%m%d").astype(int)
                with engine.begin() as conn:            # one transaction: all or nothing
                    have = set(pd.read_sql("SELECT date_id FROM dim_date", conn).date_id)
                    d = new[["date_id", "full_date"]].drop_duplicates()
                    d = d[~d.date_id.isin(have)]
                    if len(d):
                        pd.DataFrame({"date_id": d.date_id, "full_date": d.full_date.dt.date,
                                      "year": d.full_date.dt.year, "month": d.full_date.dt.month,
                                      "day_of_week": d.full_date.dt.day_name()}
                                     ).to_sql("dim_date", conn, if_exists="append", index=False)
                    new[["date_id", "product_id", "region_id", "units_sold"]].to_sql(
                        "fact_sales", conn, if_exists="append", index=False, chunksize=2000, method="multi")
                    new[["date_id", "product_id", "region_id", "units_on_hand"]].to_sql(
                        "fact_inventory", conn, if_exists="append", index=False, chunksize=2000, method="multi")
                forecast.run_forecast(engine)          # rebuild the forecast with the new days
                risk.run_risk(engine)                  # recompute the flags
                st.cache_data.clear()                  # the KPI views update by themselves
                st.session_state["upload_msg"] = (
                    f"Loaded {len(new)} rows. KPIs, forecast and risk flags are refreshed.")
                st.rerun()
