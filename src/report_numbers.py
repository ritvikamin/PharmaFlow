"""
report_numbers.py - reads the REAL results out of MySQL and writes two files:
    RESULTS.md          every number, so you can check the resume against it
    INTERVIEW_PREP.md   resume bullets + 2-minute pitch + Q&A, with those numbers filled in

Run:   python src/report_numbers.py     (run_all.py already does this at the end)
Nothing is typed in by hand: if a number is in the bullets, it came from your database.
"""
import os
import pandas as pd
from sqlalchemy import text
import config

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = ["dim_date", "dim_product", "dim_site", "dim_region",
          "fact_sales", "fact_inventory", "fact_shipments"]


def collect(engine):
    n = {}
    with engine.connect() as c:
        counts = {t: c.execute(text(f"SELECT COUNT(*) FROM {t}")).scalar() for t in TABLES}
        n["views"] = c.execute(text(
            "SELECT COUNT(*) FROM information_schema.views WHERE table_schema = :d"),
            {"d": config.DB_NAME}).scalar()
    n["counts"] = counts
    n["total_rows"] = sum(counts.values())
    n["fact_rows"] = counts["fact_sales"] + counts["fact_inventory"] + counts["fact_shipments"]
    n["products"], n["sites"], n["regions"] = counts["dim_product"], counts["dim_site"], counts["dim_region"]
    d = pd.read_sql("""SELECT MIN(d.full_date) a, MAX(d.full_date) b, COUNT(DISTINCT d.date_id) n
                       FROM fact_sales s JOIN dim_date d ON d.date_id = s.date_id""", engine).iloc[0]
    n["first_day"], n["last_day"], n["days"] = str(d["a"]), str(d["b"]), int(d["n"])

    so = pd.read_sql("SELECT * FROM v_stockout_rate_region", engine)
    n["stockout_overall"] = 100 * so.stockout_days.sum() / so.product_days.sum()
    worst = so.sort_values("stockout_rate_pct").iloc[-1]
    n["stockout_worst_region"], n["stockout_worst_pct"] = worst.region_name, float(worst.stockout_rate_pct)

    ot = pd.read_sql("SELECT * FROM v_on_time_delivery_site ORDER BY on_time_pct", engine)
    n["late_site"], n["late_site_pct"] = ot.iloc[0].site_name, float(ot.iloc[0].on_time_pct)
    others = ot.iloc[1:]
    n["others_lo"], n["others_hi"] = float(others.on_time_pct.min()), float(others.on_time_pct.max())

    v = pd.read_sql("SELECT * FROM forecast_validation WHERE scope = 'All regions'", engine).set_index("model")
    n["wape_ma"] = float(v.loc["moving_average_14d", "daily_wape_pct"])
    n["wape_naive"] = float(v.loc["naive_last_day", "daily_wape_pct"])
    n["wape_snaive"] = float(v.loc["seasonal_naive_7d", "daily_wape_pct"])
    n["tot_ma"] = float(v.loc["moving_average_14d", "total30_wape_pct"])
    n["tot_naive"] = float(v.loc["naive_last_day", "total30_wape_pct"])
    n["bias_ma"] = float(v.loc["moving_average_14d", "bias_pct"])
    n["gain_vs_naive"] = 100 * (n["wape_naive"] - n["wape_ma"]) / n["wape_naive"]

    risk = pd.read_sql("SELECT * FROM stock_risk ORDER BY days_until_empty", engine)
    n["pairs"] = len(risk)
    n["at_risk"] = int((risk.status == "At risk").sum())
    n["excess"] = int((risk.status == "Excess").sum())
    top = risk.iloc[0]
    n["top_item"] = f"{top.product_name} in {top.region_name} ({top.days_until_empty:.1f} days)"
    n["forecast_rows"] = int(pd.read_sql("SELECT COUNT(*) c FROM forecast_daily", engine).c[0])
    th = pd.read_sql("SELECT * FROM kpi_thresholds", engine).iloc[0]
    n["risk_days"], n["excess_days"] = int(th.risk_days), int(th.excess_days)
    return n


def f1(x):
    return f"{x:.1f}"


def results_md(n):
    c = n["counts"]
    lines = ["# PharmaFlow - real numbers from the last run", "",
             "All data is SYNTHETIC. Generated by this project's own script.", "",
             "| Item | Value |", "|---|---|"]
    for t in TABLES:
        lines.append(f"| rows in {t} | {c[t]:,} |")
    lines += [
        f"| total rows loaded | {n['total_rows']:,} |",
        f"| data window | {n['first_day']} to {n['last_day']} ({n['days']} days) |",
        f"| medicines / warehouses / plants | {n['products']} / {n['regions']} / {n['sites']} |",
        f"| SQL views | {n['views']} |",
        "| business KPIs | 4 (days of cover, stockout rate, on-time %, excess vs insufficient stock) |",
        f"| overall stockout rate | {n['stockout_overall']:.2f}% |",
        f"| worst region stockout rate | {n['stockout_worst_region']} {n['stockout_worst_pct']:.2f}% |",
        f"| {n['late_site']} on-time delivery | {n['late_site_pct']}% (other plants {n['others_lo']}% to {n['others_hi']}%) |",
        f"| forecast rows saved | {n['forecast_rows']:,} |",
        f"| backtest error, 14-day moving average | {f1(n['wape_ma'])}% (daily WAPE) |",
        f"| backtest error, naive last-day baseline | {f1(n['wape_naive'])}% |",
        f"| backtest error, seasonal-naive baseline | {f1(n['wape_snaive'])}% |",
        f"| error on 30-day totals, moving average vs naive | {f1(n['tot_ma'])}% vs {f1(n['tot_naive'])}% |",
        f"| moving-average bias | {n['bias_ma']:+.1f}% |",
        f"| product-region pairs scored | {n['pairs']} |",
        f"| flagged at risk (< {n['risk_days']} days) | {n['at_risk']} |",
        f"| flagged excess (> {n['excess_days']} days) | {n['excess']} |",
        f"| most urgent item | {n['top_item']} |"]
    return "\n".join(lines) + "\n"


def interview_md(n):
    text_ = open(os.path.join(ROOT, "docs", "interview_template.md"), encoding="utf-8").read()
    values = {
        "total_rows": f"{n['total_rows']:,}", "fact_rows": f"{n['fact_rows']:,}",
        "products": n["products"], "regions": n["regions"], "sites": n["sites"],
        "days": n["days"], "views": n["views"],
        "late_site": n["late_site"], "late_pct": f"{n['late_site_pct']:.0f}",
        "others_lo": f"{n['others_lo']:.0f}", "others_hi": f"{n['others_hi']:.0f}",
        "wape_ma": f1(n["wape_ma"]), "wape_naive": f1(n["wape_naive"]),
        "wape_snaive": f1(n["wape_snaive"]), "tot_ma": f1(n["tot_ma"]), "tot_naive": f1(n["tot_naive"]),
        "bias_ma": f"{n['bias_ma']:+.1f}", "gain": f"{n['gain_vs_naive']:.0f}",
        "pairs": n["pairs"], "at_risk": n["at_risk"], "excess": n["excess"],
        "risk_days": n["risk_days"], "excess_days": n["excess_days"],
        "stockout_overall": f"{n['stockout_overall']:.1f}",
        "worst_region": n["stockout_worst_region"], "worst_pct": f"{n['stockout_worst_pct']:.1f}",
        "top_item": n["top_item"],
    }
    for k, v in values.items():
        text_ = text_.replace(f"[[{k}]]", str(v))
    return text_


def main():
    engine = config.get_engine()
    n = collect(engine)
    with open(os.path.join(ROOT, "RESULTS.md"), "w", encoding="utf-8") as f:
        f.write(results_md(n))
    with open(os.path.join(ROOT, "INTERVIEW_PREP.md"), "w", encoding="utf-8") as f:
        f.write(interview_md(n))
    print(results_md(n))
    print("Wrote RESULTS.md and INTERVIEW_PREP.md")


if __name__ == "__main__":
    main()
